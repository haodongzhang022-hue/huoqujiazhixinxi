"""reserve/relations — 二次整理层：金融各市场/品种间「两两互相影响」的关联量化与预测评估。

背景 (ISSUE #7):
  数据获取层 (另一 ISSUE) 提供的是「各个市场/国家/品种/交易类型/时间级别」下的独立数据。
  本层处理的是**有了数据之后**的事：
  跨市场 / 跨国家 / 跨品种 / 跨时间周期 / 同市场不同品种 / 同品种不同交易类型(现货/合约/期权)
  / 同品种不同时间级别…… 这些「不同小目录」之间的**两两双向**关联。

设计哲学:
  1. 关联是**两两、双向**的 —— A 影响 B 与 B 影响 A 是两条独立的边，分别评估；
  2. 关联强度**可以量化** —— 固定值 / 时变变量 / 模型拟合（线性、指数衰减、
     动量扩散、领先-滞后、波动溢出、向量回归……），由 `model` 字段声明；
  3. 必须**验证预测能力** —— 用历史数据滚动回测，输出「模型预测的影响曲线」
     vs「实际影响曲线」逐点对比 + 误差统计，回答“预测能力到底够不够”，驱动后续迭代。

模块:
  dims        维度定义与解析 (市场/国家/品种/交易类型/时间级别 -> 目录 key)
  frame       矩阵定义: 目标集 -> 全两两有序对 (排除自环)
  engine      关联评估引擎: 相关系数 / 领先-滞后 / 波动溢出 / 模型拟合 / 滚动相关
              / 结构突变 / 事件研究 / 自相关
  store       关联矩阵持久化 (JSON, 兼容 LanceDB 表结构预留)
  compare     预测 vs 实际 曲线对比 + 误差统计 (验证预测能力) + 多模型自动择优
  network     传导网络分析: 节点中心性 / 强关联簇 / 传导路径 (站在矩阵之上的全局视角)
  demo        内置演示数据与端到端演示 (python -m reserve.relations.demo)
  schemas     结果结构化契约 (Pydantic)
"""

